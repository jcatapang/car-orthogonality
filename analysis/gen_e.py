"""LEACE and Sigma^{-1} filter conditions on every label set -> tables/tab_leace.tex + numbers_leace.tex.
Usage: python gen_e.py OUTDIR car_audit2_G_*.json"""
import json, sys, os
import numpy as np
OUT = sys.argv[1]; D = {}
for p in sys.argv[2:]: D.update(json.load(open(p)))
NICE = {"roberta-base": "RoBERTa-base", "roberta-large": "RoBERTa-large", "bert-base-uncased": "BERT-base",
        "gpt2": "GPT-2", "gpt2-medium": "GPT-2-medium", "EleutherAI/pythia-160m": "Pythia-160M", "EleutherAI/pythia-410m": "Pythia-410M", "Qwen/Qwen2.5-7B": "Qwen2.5-7B", "Qwen/Qwen2.5-14B": "Qwen2.5-14B", "meta-llama/Llama-3.1-8B": "Llama-3.1-8B"}
R = {}   # (dn, kind, cond, model) -> list of (|rc|, auc)
for key, v in D.items():
    ds, model, l = key.split("|")
    for dn, kinds in (v.get("analysis") or {}).items():
        for kind, conds in kinds.items():
            for cn, m in conds.items():
                rc = [abs(m[k]["mean"]) for k in m if k.startswith("median_r_cond_") and "_z_" not in k]
                au = [m[k]["mean"] for k in m if k.startswith("auc_")]
                R.setdefault((dn, kind, cn, model), []).append((np.nanmean(rc), np.nanmean(au) if au else np.nan))
models = sorted({k[3] for k in R})
def pm(dn, kind, cn, j=0):
    return {m: float(np.nanmean([x[j] for x in R[(dn, kind, cn, m)]])) for m in models if (dn, kind, cn, m) in R}
def mm(dn, kind, cn, j=0):
    v = pm(dn, kind, cn, j); return float(np.mean(list(v.values()))) if v else float("nan")
DSN = [("presence", "Topic"), ("stereo", "Stereotype"), ("factorial", "Factorial")]
COLS = [("dom", "original", "DoM"), ("dom", "euclid_orth", "Eucl."), ("dom", "sigma_orth", r"$\Sigma$-GS"),
        ("dom", "leace", "LEACE"), ("dom", "filter_inv", r"$\Sigma^{-1}$"), ("dom", "sigmaW_orth", r"$\Sigma_W$-GS"),
        ("lr", "original", "LR"), ("lr", "random_sigma", "Rand.")]
L = [r"\begin{table}[t]", r"\centering\small", r"\setlength{\tabcolsep}{3pt}",
     r"\caption{Mean $|r_{\mathrm{cond}}|$ (AUC below) by label set, averaged over the %d models. DoM columns read the difference of means under each correction.}" % len(models),
     r"\label{tab:leace}", r"\begin{adjustbox}{max width=\columnwidth}", r"\begin{tabular}{l" + "c" * len(COLS) + "}", r"\toprule",
     "Labels & " + " & ".join(c[2] for c in COLS) + r" \\", r"\midrule"]
for dn, nm in DSN:
    L.append(nm + " & " + " & ".join("%.2f" % mm(dn, k, c) for k, c, _ in COLS) + r" \\")
    L.append(r"\quad AUC & " + " & ".join("%.2f" % mm(dn, k, c, 1) if c != "random_sigma" else "--" for k, c, _ in COLS) + r" \\")
L += [r"\bottomrule", r"\end{tabular}", r"\end{adjustbox}", r"\end{table}"]
os.makedirs(f"{OUT}/tables", exist_ok=True); open(f"{OUT}/tables/tab_leace.tex", "w").write("\n".join(L) + "\n")
mac = {}
for dn, nm in DSN:
    t = nm[:3]
    for k, c, tg in (("dom", "leace", "Leace"), ("dom", "sigma_orth", "Sig"), ("dom", "filter_inv", "Inv"), ("dom", "original", "DoM"), ("lr", "original", "LR"), ("lr", "random_sigma", "Rand")):
        mac[f"e{tg}{t}"] = "%.2f" % mm(dn, k, c)
    a, b = pm(dn, "dom", "leace"), pm(dn, "dom", "sigma_orth")
    mac[f"eNLeaceLeSig{t}"] = str(sum(a[m] <= b[m] + 0.01 for m in a))
    a, b = pm(dn, "dom", "filter_inv"), pm(dn, "dom", "original")
    mac[f"eNInvBelowDoM{t}"] = str(sum(a[m] < b[m] for m in a))
    mac[f"eAucInv{t}"] = "%.2f" % mm(dn, "dom", "filter_inv", 1); mac[f"eAucDoM{t}"] = "%.2f" % mm(dn, "dom", "original", 1)
mac["eNModels"] = str(len(models))
with open(f"{OUT}/numbers_leace.tex", "w") as f:
    f.write("% AUTO-GENERATED by gen_e.py\n")
    for k, v in mac.items(): f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
print("\n".join(L[8:-4])); print(mac); print(models)
# per-model values quoted for the two largest models
with open(f"{OUT}/numbers_leace.tex", "a") as f:
    for m, tg in (("Qwen/Qwen2.5-7B", "SevenB"), ("Qwen/Qwen2.5-14B", "FourteenB")):
        v = pm("stereo", "lr", "original")
        if m in v: f.write(f"\\newcommand{{\\eLRSte{tg}}}{{{v[m]:.2f}}}\n")
