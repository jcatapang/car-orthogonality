"""Token-level steering results -> numbers_token.tex. Usage: python gen_token.py OUTDIR file.json [...]"""
import json, sys, os
import numpy as np
R = {}
for f in sys.argv[2:]: R.update(json.load(open(f)))
V = ["original", "euclid_orth", "sigma_orth", "sigma_vec", "random"]
def m_(r, v, key): return np.mean([r["steer"][k][key] for k in r["steer"] if k.split("|")[1] == v])
rat = {m: {v: m_(r, v, "absdP") / max(m_(r, v, "absdG"), 1e-9) for v in V} for m, r in R.items()}
gain = [m_(r, "sigma_vec", "absdG") / m_(r, "euclid_orth", "absdG") for r in R.values()]
allr = [x for d in rat.values() for x in d.values()]
mac = {"tokN": len(R), "tokSigBetter": sum(d["sigma_vec"] < d["euclid_orth"] for d in rat.values()),
       "tokRatioLo": f"{min(allr):.1f}", "tokRatioHi": f"{max(allr):.1f}",
       "tokGainLo": f"{min(gain):.1f}", "tokGainHi": f"{max(gain):.0f}"}
with open(os.path.join(sys.argv[1], "numbers_token.tex"), "w") as f:
    f.write("% AUTO-GENERATED by gen_token.py\n")
    for k, v in mac.items(): f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
print(mac)
