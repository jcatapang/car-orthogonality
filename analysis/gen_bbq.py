"""BBQ steering results -> numbers_bbq_auto.tex + tables/tab_bbq.tex + summary print.
Usage: python gen_bbq.py OUTDIR car_bbq_results.json [more.json]
Per target category T, vector v and strength k:
  on-target   = |change| in T's metrics; off-target = mean |change| over the other categories.
Metrics: acc_ambig, acc_disambig, bias_ambig, bias_disambig. 'Behaviour change' of a category is the mean
absolute change over these four. Selectivity = on-target change / mean off-target change.
"""
import json, sys, os
import numpy as np

OUT = sys.argv[1]
R = {}
for p in sys.argv[2:]:
    R.update(json.load(open(p)))
VN = ["dom", "lr", "euclid", "sigvec", "random", "random_big"]
LBL = {"dom": "Difference of means", "lr": "LR filter $\\w$", "euclid": "Euclid.-orth.\\ filter $\\w^E$",
       "sigvec": "Pattern $\\Sigma\\w^\\Sigma$", "random": "Random"}
MET = ["acc_ambig", "acc_disambig", "bias_ambig", "bias_disambig"]
NICE = {"Qwen/Qwen2.5-1.5B-Instruct": "Qwen2.5-1.5B-Instruct", "Qwen/Qwen2.5-3B-Instruct": "Qwen2.5-3B-Instruct"}


def change(base, st, c, m):
    return st["per_cat"][c][m] - base[c][m]


recs = []
for model, res in R.items():
    base = res["baseline"]; cats = list(base)
    for key, st in res["steer"].items():
        T, vn, k = key.split("|"); k = float(k)
        on = {m: change(base, st, T, m) for m in MET}
        off = {m: np.mean([abs(change(base, st, c, m)) for c in cats if c != T]) for m in MET}
        recs.append(dict(model=model, T=T, vn=vn, k=k, norm=st["norm"], fc=st["frac_changed"],
                         on_beh=np.mean([abs(on[m]) for m in MET]), off_beh=np.mean([off[m] for m in MET]),
                         on_bias=on["bias_ambig"], on_absbias=abs(on["bias_ambig"]), off_absbias=off["bias_ambig"],
                         on_accd=on["acc_disambig"], off_accd=off["acc_disambig"]))


def agg(vn, k, key, model=None):
    a = [r[key] for r in recs if r["vn"] == vn and r["k"] == k and (model is None or r["model"] == model)]
    return float(np.mean(a)) if a else float("nan")


ks = sorted({r["k"] for r in recs})
models = list(R)
print("baseline:")
for m in models:
    for c, v in R[m]["baseline"].items():
        print(f"  {m:30s} {c:16s} " + " ".join(f"{x}={v.get(x, float('nan')):+.3f}" for x in MET))
for m in models + [None]:
    print(f"\n=== {m or 'ALL'}")
    for k in ks:
        for vn in VN:
            on, off = agg(vn, k, "on_beh", m), agg(vn, k, "off_beh", m)
            print(f"  k={k:g} {vn:7s} frac_changed={agg(vn, k, 'fc', m):.3f} on={on:.3f} off={off:.3f} sel={on / max(off, 1e-9):.2f} "
                  f"dBiasAmb(T)={agg(vn, k, 'on_bias', m):+.3f} |dBiasAmb| off={agg(vn, k, 'off_absbias', m):.3f} "
                  f"dAccDis(T)={agg(vn, k, 'on_accd', m):+.3f} off={agg(vn, k, 'off_accd', m):.3f} norm={agg(vn, k, 'norm', m):.1f}")
print("\nper target (k=max):")
kM = max(ks)
for m in models:
    for T in R[m]["baseline"]:
        print(f"  {T:16s} " + "  ".join(f"{vn}:{np.mean([r['on_beh'] for r in recs if r['model']==m and r['T']==T and r['vn']==vn and r['k']==kM]):.3f}/"
                                         f"{np.mean([r['off_beh'] for r in recs if r['model']==m and r['T']==T and r['vn']==vn and r['k']==kM]):.3f}" for vn in VN))

json.dump(recs, open(os.path.join(OUT, "bbq_recs.json"), "w"), indent=1)

# macros for the paper (v2: biased-answer directions, largest strength)
kM = max(ks)
def a_(vn, key): return agg(vn, kM, key)
sel = {vn: a_(vn, "on_beh") / max(a_(vn, "off_beh"), 1e-9) for vn in VN}
mac = {"bbqModel": ", ".join(NICE.get(m, m) for m in R), "bbqK": f"{kM:g}",
       "bbqSelLo": f"{min(sel.values()):.1f}", "bbqSelHi": f"{max(sel.values()):.1f}",
       "bbqMaxOnBias": f"{max(abs(a_(vn, 'on_bias')) for vn in VN):.3f}",
       "bbqFcSigvec": f"{100 * a_('sigvec', 'fc'):.0f}", "bbqFcRandBig": f"{100 * a_('random_big', 'fc'):.0f}",
       "bbqFcDom": f"{100 * a_('dom', 'fc'):.0f}", "bbqFcEucl": f"{100 * a_('euclid', 'fc'):.0f}", "bbqFcRand": f"{100 * a_('random', 'fc'):.0f}",
       "bbqNCat": f"{len(next(iter(R.values()))['baseline'])}"}
with open(os.path.join(OUT, "numbers_bbq.tex"), "w") as f:
    f.write("% AUTO-GENERATED by gen_bbq.py\n")
    for k, v in mac.items(): f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
print(mac)
